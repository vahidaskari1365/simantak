export function getProduct(slug: string): Product | undefined {
  return products.find((product) => product.slug === slug);
}

export function categoryOf(id: CategoryId): Category {
  return productCategories.find((category) => category.id === id) ?? productCategories[0];
}

export function productsByCategory(id: CategoryId): Product[] {
  return products.filter((product) => product.category === id);
}

export function relatedProducts(slug: string, count = 3): Product[] {
  const current = getProduct(slug);
  if (!current) return products.slice(0, count);
  const sameCategory = products.filter((p) => p.category === current.category && p.slug !== slug);
  const others = products.filter((p) => p.category !== current.category && p.slug !== slug);
  return [...sameCategory, ...others].slice(0, count);
}

